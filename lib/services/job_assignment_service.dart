/// Service class responsible for automatically assigning jobs to distributors
/// based on their availability and index order
class JobAssignmentService {
  final ScheduleProvider scheduleProvider;
  final DayOffProvider? dayOffProvider;

  JobAssignmentService(this.scheduleProvider, {this.dayOffProvider});

  /// Rounds up man-days (2.3 → 3)
  int roundUpManDays(double manDays) {
    return manDays.ceil();
  }

  /// Find distributors that don't have jobs assigned on a specific date.
  /// Only considers active distributors for allocation.
  List<Distributor> findAvailableDistributors(DateTime date) =>
      [for (final c in candidatesFor(date)) c.distributor];

  /// Every distributor who could take a job on [date], free ones first, each
  /// in index order. Distributors who already have a job that day are only
  /// included when [allowOccupied] is true (Junk & Stuff / Happy Sun work,
  /// where one person can take several jobs a day). Inactive and day-off
  /// distributors are never offered.
  List<DistributorCandidate> candidatesFor(DateTime date,
      {bool allowOccupied = false}) {
    final occupied = scheduleProvider
        .getJobsForDate(date)
        .map((job) => job.distributorId)
        .toSet();
    final eligible = scheduleProvider.distributors
        .where((d) =>
            d.status == DistributorStatus.active &&
            !(dayOffProvider?.isDayOff(d.id, date) ?? false) &&
            (allowOccupied || !occupied.contains(d.id)))
        .toList()
      ..sort((a, b) {
        final byOccupied = (occupied.contains(a.id) ? 1 : 0)
            .compareTo(occupied.contains(b.id) ? 1 : 0);
        return byOccupied != 0 ? byOccupied : a.index.compareTo(b.index);
      });
    return [
      for (final d in eligible)
        DistributorCandidate(
          distributor: d,
          hasJobThatDay: occupied.contains(d.id),
        ),
    ];
  }

  /// Calculate job assignments for a given number of man-days starting from a date.
  ///
  /// With [allowOccupied], distributors who already have a job that day are
  /// used once the free ones run out, so the job keeps its booked date rather
  /// than spilling onto the next day.
  List<JobAssignment> calculateJobAssignments({
    required String client,
    required double manDays,
    required DateTime startDate,
    String? workingArea,
    bool allowOccupied = false,
  }) {
    final assignments = <JobAssignment>[];
    int remainingDays = roundUpManDays(manDays);
    DateTime currentDate = startDate;
    // Bounded so a schedule with nobody eligible fails instead of spinning.
    final lastDate = DateTime(startDate.year, startDate.month + 3, startDate.day);

    while (remainingDays > 0) {
      if (currentDate.isAfter(lastDate)) return const [];
      final availableDistributors = [
        for (final c in candidatesFor(currentDate,
            allowOccupied: allowOccupied))
          c.distributor,
      ];

      if (availableDistributors.isEmpty) {
        // No available distributors for this date, move to next day
        currentDate =
            DateTime(currentDate.year, currentDate.month, currentDate.day + 1);
        continue;
      }

      // Assign jobs to available distributors (up to remaining days needed)
      final distributorsToAssign =
          availableDistributors.take(remainingDays).toList();

      for (final distributor in distributorsToAssign) {
        assignments.add(JobAssignment(
          client: client,
          distributorId: distributor.id,
          distributorName: distributor.name,
          date: currentDate,
          workingArea: workingArea ?? 'To be assigned', // Default placeholder
        ));
        remainingDays--;
      }

      // If we still have remaining days, move to next day
      if (remainingDays > 0) {
        currentDate =
            DateTime(currentDate.year, currentDate.month, currentDate.day + 1);
      }
    }

    return assignments;
  }

  /// Convert job assignments to actual Job objects
  List<Job> createJobsFromAssignments(List<JobAssignment> assignments) {
    return assignments
        .map((assignment) => Job(
              id: '', // Will be generated by Firestore
              clients: [assignment.client],
              workingAreas: [assignment.workingArea],
              // Empty unless a regular client plan supplied the day's areas.
              workMaps: assignment.workMaps,
              distributorId: assignment.distributorId,
              date: assignment.date,
              statusId: 'logged', // Use default scheduled status
            ))
        .toList();
  }

  /// Assignments for a regular client's plan: one per slot per man day,
  /// carrying copies of that day's polygons from [map].
  ///
  /// Each slot's day k goes on the k-th date from [startDate] on which
  /// someone can take it, and keeps the same distributor across its days
  /// when that person is free. Two slots never share a distributor on one
  /// date unless [allowOccupied] and nobody else is left. Polygons the plan
  /// names but [map] no longer has are skipped. Empty when some day cannot
  /// be placed within three months.
  List<JobAssignment> calculateRegularClientAssignments({
    required String client,
    required RegularClient plan,
    required ShareableMap map,
    required DateTime startDate,
    bool allowOccupied = false,
  }) {
    final polygonsById = <String, CustomPolygon>{
      for (final layer in map.layers) ...{
        for (final p in layer.polygons)
          if ((p.id ?? '').isNotEmpty) p.id!: p,
        // Points (handout and poster spots) go on the job as point-type
        // polygons carrying the point's id.
        for (final pt in layer.points)
          if (pt.id.isNotEmpty) pt.id: mapPointAsWorkMap(pt),
      },
    };
    final start = DateTime(startDate.year, startDate.month, startDate.day);
    final lastDate = DateTime(start.year, start.month + 3, start.day);
    final usedOn = <DateTime, Set<String>>{};
    final assignments = <JobAssignment>[];

    for (final slot in plan.slots) {
      String? keep;
      var date = start;
      for (var k = 0; k < slot.days.length; k++) {
        Distributor? pick;
        while (pick == null) {
          if (date.isAfter(lastDate)) return const [];
          final used = usedOn[date] ?? const <String>{};
          final all = [
            for (final c in candidatesFor(date, allowOccupied: allowOccupied))
              c.distributor,
          ];
          var pool = [for (final d in all) if (!used.contains(d.id)) d];
          if (pool.isEmpty && allowOccupied) pool = all;
          if (pool.isEmpty) {
            date = DateTime(date.year, date.month, date.day + 1);
            continue;
          }
          pick = pool.firstWhere((d) => d.id == keep,
              orElse: () => pool.first);
        }
        final polygons = [
          for (final id in slot.days[k].polygonIds)
            if (polygonsById[id] != null) polygonsById[id]!,
        ];
        assignments.add(JobAssignment(
          client: client,
          distributorId: pick.id,
          distributorName: pick.name,
          date: date,
          workingArea: polygons.isEmpty
              ? 'To be assigned'
              : polygons.map((p) => p.name).join(', '),
          label: slot.days.length == 1
              ? slot.label
              : '${slot.label} · Day ${k + 1}',
          workMaps: polygons,
        ));
        (usedOn[date] ??= <String>{}).add(pick.id);
        keep = pick.id;
        date = DateTime(date.year, date.month, date.day + 1);
      }
    }
    return assignments;
  }

  /// Main method to create job assignments from a JobListItem
  Future<List<Job>> createJobAssignmentsFromJobList(
      JobListItem jobListItem) async {
    final assignments = calculateJobAssignments(
      client: jobListItem.client,
      manDays: jobListItem.manDays,
      startDate: jobListItem.date,
      // For now, we'll use default work area settings
      // These can be edited later on the schedule
      workingArea: 'To be assigned',
    );

    return createJobsFromAssignments(assignments);
  }
}

/// A distributor offered for an assignment on a given date.
class DistributorCandidate {
  final Distributor distributor;

  /// Already has a schedule job that day.
  final bool hasJobThatDay;

  const DistributorCandidate({
    required this.distributor,
    required this.hasJobThatDay,
  });
}

/// Data class representing a job assignment before it becomes a Job object
class JobAssignment {
  final String client;
  final String distributorId;
  final String distributorName;
  final DateTime date;
  final String workingArea;

  /// What this row is in a regular client plan ("Distributor 1 · Day 2"),
  /// or null for a plain man-day assignment.
  final String? label;

  /// Areas the schedule job is created with (copies). Empty for a plain
  /// man-day assignment.
  final List<CustomPolygon> workMaps;

  JobAssignment({
    required this.client,
    required this.distributorId,
    required this.distributorName,
    required this.date,
    required this.workingArea,
    this.label,
    this.workMaps = const [],
  });

  JobAssignment copyWith({String? distributorId, String? distributorName}) {
    return JobAssignment(
      client: client,
      distributorId: distributorId ?? this.distributorId,
      distributorName: distributorName ?? this.distributorName,
      date: date,
      workingArea: workingArea,
      label: label,
      workMaps: workMaps,
    );
  }

  @override
  String toString() {
    return 'JobAssignment(client: $client, distributor: $distributorName, date: $date)';
  }
}
