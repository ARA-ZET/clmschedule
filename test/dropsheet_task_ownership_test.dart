// Ownership rules for dropsheet tasks linked to a job-list item.
//
// These two predicates decide whether the job-list sync may delete or reword
// a task. Getting them wrong is user-visible data loss: a task that vanishes
// moments after it is added, or an edit that reverts on the next sync pass.
// They are pure functions over `typeData`, so they are cheap to pin down here.
import 'package:flutter_test/flutter_test.dart';

import 'package:clmschedule/models/dropsheet_task.dart';

DropsheetTask taskWith(Map<String, dynamic> typeData) => DropsheetTask(
      id: 't1',
      type: DropsheetTaskType.pickFlyers,
      sourceJobListItemId: 'item1',
      typeData: typeData,
    );

void main() {
  group('isUserCreatedJobListTask', () {
    test('a task built by the editor is user-created', () {
      // The editor stamps _jlManual when the user links an item by hand.
      expect(
        taskWith({
          'jobListItemId': 'item1',
          DropsheetTask.kJobListManualKey: true,
        }).isUserCreatedJobListTask,
        isTrue,
      );
    });

    test('a task generated by the sync is not user-created', () {
      // _jlFp is written only by DropsheetProvider._buildJobListTask.
      expect(
        taskWith({
          'jobListItemId': 'item1',
          DropsheetTask.kJobListFingerprintKey: 'abc123',
        }).isUserCreatedJobListTask,
        isFalse,
      );
    });

    test('a legacy hand-linked task with no markers is user-created', () {
      // Tasks created before the ownership model existed carry neither key.
      // Treating them as sync-owned is what deleted them on the next pass.
      expect(
        taskWith({'jobListItemId': 'item1'}).isUserCreatedJobListTask,
        isTrue,
      );
    });

    test('a hand-built task stays user-created after a sync refresh', () {
      // A refresh stamps _jlFp. Without _jlManual surviving that rebuild the
      // task would silently become sync-owned and be deletable.
      expect(
        taskWith({
          'jobListItemId': 'item1',
          DropsheetTask.kJobListFingerprintKey: 'abc123',
          DropsheetTask.kJobListManualKey: true,
        }).isUserCreatedJobListTask,
        isTrue,
      );
    });
  });

  group('hasUserEdits', () {
    test('false for a freshly synced task', () {
      expect(
        taskWith({DropsheetTask.kJobListFingerprintKey: 'abc123'}).hasUserEdits,
        isFalse,
      );
    });

    test('true once the editor records a rewording', () {
      expect(
        taskWith({
          DropsheetTask.kJobListFingerprintKey: 'abc123',
          DropsheetTask.kUserEditedKey: true,
        }).hasUserEdits,
        isTrue,
      );
    });
  });

  group('round-trips through Firestore serialisation', () {
    test('ownership markers survive toMap/fromMap', () {
      final original = taskWith({
        'jobListItemId': 'item1',
        DropsheetTask.kJobListManualKey: true,
        DropsheetTask.kUserEditedKey: true,
      });
      final restored = DropsheetTask.fromMap(original.toMap());

      expect(restored.isUserCreatedJobListTask, isTrue);
      expect(restored.hasUserEdits, isTrue);
      expect(restored.sourceJobListItemId, 'item1');
    });

    test('a per-task service time survives toMap/fromMap', () {
      // serviceTimeMinutes is never derived from the job-list item, so it has
      // to round-trip intact — it used to be dropped on every re-sync.
      final restored = DropsheetTask.fromMap(
        DropsheetTask(id: 't1', serviceTimeMinutes: 25).toMap(),
      );
      expect(restored.serviceTimeMinutes, 25);
    });
  });

  group('notes on distributor tasks', () {
    DropsheetTask dropOff(String details) => DropsheetTask(
          id: 'd1',
          type: DropsheetTaskType.dropOff,
          details: details,
          location: 'Woodstock',
          contact: 'Thabo',
          typeData: const {
            'distributorName': 'Thabo',
            'workArea': 'Woodstock',
          },
        );

    test('legacy auto-filled name / work area reads as no notes', () {
      expect(dropOff('Thabo').notes, '');
      expect(dropOff('Woodstock').notes, '');
    });

    test('a note the user typed is kept', () {
      expect(
          dropOff('2 boxes, gate code 1234').notes, '2 boxes, gate code 1234');
    });

    test('non-distributor tasks are never treated as auto-filled', () {
      const t = DropsheetTask(
        id: 'c1',
        type: DropsheetTaskType.pickFlyers,
        details: 'Thabo',
        contact: 'Thabo',
      );
      expect(t.notes, 'Thabo');
    });
  });

  group('detailsText', () {
    DropsheetTask task(DropsheetTaskType type, String details) => DropsheetTask(
          id: 'd1',
          type: type,
          details: details,
          contact: 'Thabo',
          typeData: const {'distributorName': 'Thabo', 'workArea': 'Woodstock'},
        );

    test('drop-offs and pick-ups lead with the distributor name', () {
      expect(task(DropsheetTaskType.dropOff, '').detailsText, 'Thabo');
      expect(task(DropsheetTaskType.pickUp, '2 boxes').detailsText,
          'Thabo · 2 boxes');
    });

    test('legacy auto-filled name is not shown twice', () {
      expect(task(DropsheetTaskType.dropOff, 'Thabo').detailsText, 'Thabo');
    });

    test('other types show just the notes', () {
      expect(task(DropsheetTaskType.distribute, 'x').detailsText, 'x');
    });
  });
}
